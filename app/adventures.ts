export type AdventureTrait =
  | 'kindness'
  | 'curiosity'
  | 'courage'
  | 'creativity';

export type AdventureChoice = {
  label: string;
  result: string;
  clue: string;
  trait: AdventureTrait;
};

export type AdventureScene = {
  chapter: string;
  title: string;
  body: string;
  echoes?: Record<AdventureTrait, string>;
  choices: AdventureChoice[];
};

export type AdventureStory = {
  id: string;
  icon: string;
  title: string;
  desc: string;
  color: string;
  reward: string;
  scenes: AdventureScene[];
  endings: Record<AdventureTrait, string>;
};

export type AdventureDecision = AdventureChoice & {
  chapter: string;
  sceneTitle: string;
};

